const ColorRow: React.FC<{
  label: string;
  value: string;
  onChange: (v: string) => void;
}> = ({ label, value, onChange }) => {
  const pickerRef = useRef<HTMLInputElement>(null);
  const [draft, setDraft] = useState(value);
  useEffect(() => setDraft(value), [value]);
  return (
    <div style={{ alignItems: 'center', display: 'flex', gap: 8, padding: '4px 0' }}>
      <div
        role="button"
        title="Open color picker"
        onClick={() => pickerRef.current?.click()}
        style={{
          backgroundColor: value,
          border: '1px solid rgba(255,255,255,0.15)',
          borderRadius: 4,
          cursor: 'pointer',
          flexShrink: 0,
          height: 24,
          width: 24,
        }}
      />
      <input
        ref={pickerRef}
        type="color"
        value={value}
        onChange={e => { onChange(e.target.value); setDraft(e.target.value); }}
        style={{ height: 0, opacity: 0, pointerEvents: 'none', position: 'absolute', width: 0 }}
      />
      <input
        type="text"
        value={draft}
        onChange={e => {
          setDraft(e.target.value);
          if (/^#[0-9A-Fa-f]{6}$/.test(e.target.value)) onChange(e.target.value);
        }}
        style={ei.hex}
        spellCheck={false}
      />
      <span style={ei.label}>{label}</span>
    </div>
  );
};

