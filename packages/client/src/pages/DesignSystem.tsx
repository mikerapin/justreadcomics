// ─── Export generators ────────────────────────────────────────────────────────

const toSCSS = (t: Tokens): string => {
  const ff = `'${t.type.fontFamily}', -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif`;
  const l = t.type.levels;
  return [
    `// Generated by /design`,
    `// Paste into packages/client/src/styles/_variables.scss`,
    ``,
    `$color-accent:    ${t.colors.accent};`,
    `$color-primary:   ${t.colors.primary};`,
    `$color-secondary: ${t.colors.secondary};`,
    ``,
    `$font-family-base:     ${ff};`,
    `$headings-font-family: ${ff};`,
    `$font-weight-base:     ${l.body.weight};`,
    `$headings-line-height: 1.2;`,
    `$line-height-base:     1.6;`,
    ``,
    `$h1-font-size: ${l.h1.size}rem;`,
    `$h2-font-size: ${l.h2.size}rem;`,
    `$h3-font-size: ${l.h3.size}rem;`,
    `$h4-font-size: ${l.h4.size}rem;`,
    `$h5-font-size: ${l.h5.size}rem;`,
    `$h6-font-size: ${l.h6.size}rem;`,
    ``,
    `$border-radius:      ${(t.radii.normal.value / 16).toFixed(4)}rem;  // ${t.radii.normal.value}px`,
    `$border-radius-sm:   ${(t.radii.tight.value  / 16).toFixed(4)}rem;  // ${t.radii.tight.value}px`,
    `$border-radius-lg:   ${(t.radii.soft.value   / 16).toFixed(4)}rem;  // ${t.radii.soft.value}px`,
    `$border-radius-pill: 50rem;`,
    ``,
    `// — Color overrides — uncomment when ready —`,
    `// $body-bg:    ${t.colors.backgroundBase};`,
    `// $body-color: ${t.colors.textOnDark};`,
    `// $primary:    ${t.colors.primary};`,
    `// $secondary:  ${t.colors.secondary};`,
  ].join('\n');
};

const toJSON = (t: Tokens): string => {
  const ff = `'${t.type.fontFamily}', -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif`;
  const l = t.type.levels;
  return JSON.stringify({
    colors: {
      backgroundBase:  t.colors.backgroundBase,
      textOnDark:      t.colors.textOnDark,
      accentColor:     t.colors.accent,
      primaryAction:   t.colors.primary,
      secondaryAction: t.colors.secondary,
    },
    typography: Object.fromEntries(
      (Object.keys(l) as Array<keyof typeof l>).map(k => [k, {
        fontFamily: ff,
        fontWeight: l[k].weight,
        fontSize:   `${l[k].size}rem`,
      }])
    ),
    radius: {
      tight:  `${t.radii.tight.value}px`,
      normal: `${t.radii.normal.value}px`,
      soft:   `${t.radii.soft.value}px`,
    },
  }, null, 2);
};

